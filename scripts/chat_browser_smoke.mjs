// Synthetic transport + real browser/API/SQLite. No live OAuth or inference.
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const {chromium}=await import(process.env.RYOSHU_PLAYWRIGHT_MODULE||'playwright');
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const output=path.join(root,'.local','chat-browser',new Date().toISOString().replace(/[:.]/g,'-'));
await fs.mkdir(output,{recursive:true});
const log=[],checks=[];
const child=spawn(process.env.RYOSHU_QA_PYTHON||'python',[path.join(root,'scripts/serve_chat_qa.py'),'--output',path.join(output,'runtime')],{cwd:root,windowsHide:true,stdio:['ignore','pipe','pipe']});
const exit=new Promise(resolve=>child.once('exit',code=>resolve(code)));
child.stderr.on('data',d=>log.push(d.toString()));
let base,stopToken,browser;
try{
  let buffer='';
  const ready=await new Promise((resolve,reject)=>{
    const timer=setTimeout(()=>reject(new Error('QA startup failed '+log.join(''))),30000);
    child.once('error',reject);child.once('exit',code=>reject(new Error('QA exit '+code+' '+log.join(''))));
    child.stdout.on('data',d=>{buffer+=d.toString();let n;while((n=buffer.indexOf('\n'))>=0){const line=buffer.slice(0,n);buffer=buffer.slice(n+1);try{const value=JSON.parse(line);if(value.qa_url){clearTimeout(timer);resolve(value);}}catch{}}});
  });
  base=ready.qa_url;stopToken=ready.stop_token;
  for(let i=0;i<100;i++){try{if((await fetch(base+'/api/config')).ok)break;}catch{}await new Promise(r=>setTimeout(r,100));}
  const launch={headless:true};if(process.env.RYOSHU_BROWSER_CHANNEL)launch.channel=process.env.RYOSHU_BROWSER_CHANNEL;
  browser=await chromium.launch(launch);
  const context=await browser.newContext({viewport:{width:1280,height:900}});
  const page=await context.newPage(),errors=[],external=[];
  page.on('pageerror',e=>errors.push(e.message));
  await context.route('**/*',route=>{if(!route.request().url().startsWith('http://127.0.0.1:')&&!route.request().url().startsWith('data:')){external.push(route.request().url());return route.abort();}return route.continue();});
  await page.goto(base);await page.locator('[data-ledger-select]').first().waitFor();
  let data=await (await fetch(base+'/_qa/state')).json();const [a,b,c]=data.ids;
  await page.locator(`[data-ledger-select="${a}"]`).check();
  await page.locator(`[data-ledger-select="${b}"]`).check();
  await page.locator('[data-chat-open="selection"]').click();
  const dialog=page.locator('#chat-dialog');await dialog.locator('[data-chat="connect"]').waitFor();
  assert.equal(await dialog.locator('#chat-allow').isChecked(),false);checks.push('external consent is initially off; exactly two selected records');
  assert.match(await dialog.locator('.chat-targets summary').textContent(),/2件/);
  const popupWait=context.waitForEvent('page');await dialog.locator('[data-chat="connect"]').click();
  const popup=await popupWait;await popup.waitForLoadState();
  await dialog.locator('#chat-connection-message').filter({hasText:'接続しました'}).waitFor({state:'attached'});
  await popup.close();checks.push('synthetic OAuth loopback callback verifies a real RSA-signed identity');
  await dialog.locator('[data-chat="models"]').click();
  await dialog.locator('#chat-model option[value="synthetic-model"]').waitFor({state:'attached'});
  await dialog.locator('#chat-model').selectOption('synthetic-model');
  await dialog.locator('#chat-message').fill('選択した2件を通信費・事業割合50%に');
  await dialog.locator('#chat-form button[type="submit"]').click();
  await dialog.locator('#chat-error').filter({hasText:'送信のチェック'}).waitFor();
  data=await (await fetch(base+'/_qa/state')).json();assert.equal(data.calls.length,0);checks.push('missing external consent prevents any generation');
  await dialog.locator('#chat-allow').check();await dialog.locator('#chat-form button[type="submit"]').click();
  await dialog.locator('.chat-proposal').waitFor();
  data=await (await fetch(base+'/_qa/state')).json();
  assert.equal(data.calls.length,1);assert.equal(data.rows.find(r=>r.id===a).draft.account,'消耗品費');
  assert.equal(JSON.stringify(data.calls).includes('送信しないOCR本文'),false);
  assert.equal(JSON.stringify(data.calls).includes(c),false);checks.push('preview does not save; unselected records and OCR never enter request');
  await dialog.screenshot({path:path.join(output,'proposal-desktop.png')});
  await page.route('**/api/chat/apply',async route=>{const response=await route.fetch();assert.equal(response.status(),200);await route.abort();});
  await dialog.locator('[data-chat="apply"]').click();
  await dialog.getByRole('alert').filter({hasText:'保存されたか確認できません'}).waitFor();
  assert.equal(await dialog.locator('[data-chat="discard"]').isDisabled(),true);
  assert.equal(await dialog.locator('[data-chat="reset"]').isDisabled(),true);
  checks.push('lost apply response states unknown outcome and prevents misleading discard');
  await page.unroute('**/api/chat/apply');
  await dialog.locator('[data-chat="apply"]').click();
  await dialog.locator('.chat-messages').filter({hasText:'2件の変更を未確認で保存'}).waitFor();
  data=await (await fetch(base+'/_qa/state')).json();
  for(const id of [a,b]){const r=data.rows.find(x=>x.id===id);assert.equal(r.draft.account,'通信費');assert.equal(r.draft.business_percent,50);assert.equal(r.status,'review');}
  assert.equal(data.rows.find(r=>r.id===c).status,'confirmed');checks.push('explicit apply saves only the selected two rows as unreviewed');
  assert.equal(await dialog.locator('#chat-allow').isChecked(),false);checks.push('successful save starts a clearly marked fresh conversation with consent off');
  await dialog.locator('[data-chat="close"]').click();
  await page.locator(`[data-open-receipt="${c}"]`).click();await page.locator('[data-chat-open="detail"]').click();
  await dialog.locator('[data-chat="models"]').click();await dialog.locator('#chat-model').selectOption('synthetic-model');
  await dialog.locator('#chat-message').fill('この明細を通信費にして');await dialog.locator('#chat-allow').check();
  await dialog.locator('#chat-form button[type="submit"]').click();await dialog.locator('.chat-proposal').waitFor();
  assert.match(await dialog.locator('.chat-proposal').innerText(),/確認済み → 未確認/);
  await dialog.locator('[data-chat="apply"]').click();await dialog.locator('.chat-messages').filter({hasText:'1件の変更を未確認で保存'}).waitFor();
  data=await (await fetch(base+'/_qa/state')).json();const confirmed=data.rows.find(r=>r.id===c);
  assert.equal(confirmed.status,'review');assert.equal(confirmed.posting,null);checks.push('confirmed entry is explicitly reopened and its old journal voided');
  await page.setViewportSize({width:375,height:812});
  assert.equal(await dialog.evaluate(el=>el.scrollWidth>el.clientWidth),false);await dialog.screenshot({path:path.join(output,'chat-mobile.png')});checks.push('375px dialog has no horizontal overflow');
  await dialog.locator('[data-chat="reset"]').click();assert.equal(await dialog.locator('#chat-allow').isChecked(),false);checks.push('new conversation clears external-data consent');
  await dialog.locator('#chat-message').fill('入力中の日本語の依頼を消さない');
  await dialog.locator('[data-chat="reset"]').click();assert.equal(await dialog.locator('#chat-message').inputValue(),'入力中の日本語の依頼を消さない');checks.push('new conversation retains an unsent Japanese request');
  // Another tab changes the active connection after this screen granted consent.
  await dialog.locator('#chat-allow').check();await fetch(base+'/_qa/switch-account',{method:'POST'});
  const callsBefore=(await (await fetch(base+'/_qa/state')).json()).calls.length;
  await dialog.locator('#chat-form button[type="submit"]').click();
  await dialog.locator('#chat-error').filter({hasText:'接続先が変わりました'}).waitFor();
  assert.equal((await (await fetch(base+'/_qa/state')).json()).calls.length,callsBefore);
  assert.equal(await dialog.locator('#chat-allow').isChecked(),false);assert.equal(await dialog.locator('#chat-model').inputValue(),'');checks.push('another-tab account switch stops sending and clears model plus consent');
  await fetch(base+'/_qa/hold-login',{method:'POST'});
  await dialog.locator('.chat-connection summary').click();
  const waitingPopup=context.waitForEvent('page');await dialog.locator('[data-chat="reconnect"]').click();const held=await waitingPopup;await held.waitForLoadState();
  await dialog.locator('#chat-message').fill('接続待ちでも日本語入力を保持');
  const textarea=await dialog.locator('#chat-message').elementHandle();await textarea.focus();
  await page.waitForTimeout(3400);
  assert.equal(await textarea.evaluate(el=>el.isConnected&&document.activeElement===el),true);checks.push('login polling retains the focused Japanese input node');
  await dialog.locator('[data-chat="cancel-login"]').click();await held.close();
  await dialog.locator('.chat-connection summary').click();
  await dialog.locator('[data-chat="disconnect"]').click();await dialog.locator('#chat-connection-message').waitFor();
  const status=await (await fetch(base+'/api/chat/connection')).json();assert.equal(status.active,null);assert.equal(status.profiles.find(p=>p.id==='qa-second').signed_in,false);assert.equal(status.profiles.find(p=>p.id!=='qa-second').signed_in,true);checks.push('disconnect clears only the chosen connection and keeps other accounts separate');
  assert.deepEqual(errors,[]);assert.deepEqual(external,[]);checks.push('no browser exceptions or external browser requests');
  await fs.writeFile(path.join(output,'result.json'),JSON.stringify({scope:'Synthetic OAuth and AI. Actual browser, APIs and SQLite. No live account or inference.',checks,passed:true},null,2));
  console.log(JSON.stringify({passed:true,checks:checks.length,output},null,2));
}finally{
  if(browser)await browser.close();
  if(base&&stopToken)await fetch(base+'/_qa/stop',{method:'POST',headers:{'X-QA-Stop':stopToken}}).catch(()=>{});
  await Promise.race([exit,new Promise(resolve=>setTimeout(resolve,5000))]);
  if(child.exitCode===null)child.kill();
  await fs.writeFile(path.join(output,'server.log'),log.join(''));
}
